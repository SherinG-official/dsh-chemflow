import assert from 'node:assert/strict'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import test from 'node:test'

import { readStructure } from '../lib/view/structure.js'
import { buildViewPack } from '../lib/view/pack.js'

const dir = mkdtempSync(path.join(tmpdir(), 'chemflow-struct-'))
process.on('exit', () => rmSync(dir, { recursive: true, force: true }))

const water = `3
water
O 0.0000 0.0000 0.1173
H 0.0000 0.7572 -0.4692
H 0.0000 -0.7572 -0.4692
`

test('xyz：读原子并按距离成键', () => {
  const file = path.join(dir, 'water.xyz')
  writeFileSync(file, water, 'utf8')
  const { atoms, bonds } = readStructure(file)
  assert.equal(atoms.length, 3)
  assert.equal(atoms[0].element, 'O')
  assert.equal(bonds.length, 2)
})

test('ORCA .out：取最后一块 ANGSTROEM 坐标（优化后的几何）', () => {
  const file = path.join(dir, 'job.out')
  writeFileSync(
    file,
    [
      'some header',
      'CARTESIAN COORDINATES (ANGSTROEM)',
      '---------------------------------',
      '  O      0.000000    0.000000    5.000000',
      '  H      0.000000    0.700000    5.500000',
      '',
      'energy...',
      'CARTESIAN COORDINATES (ANGSTROEM)',
      '---------------------------------',
      '  O      0.000000    0.000000    0.117300',
      '  H      0.000000    0.757200   -0.469200',
      '  H      0.000000   -0.757200   -0.469200',
      '',
      'FINAL SINGLE POINT ENERGY',
    ].join('\n'),
    'utf8',
  )
  const { atoms } = readStructure(file)
  assert.equal(atoms.length, 3)
  assert.ok(Math.abs(atoms[0].z - 0.1173) < 1e-6)
})

test('Molden：AU 坐标换算成 Å', () => {
  const file = path.join(dir, 'job.molden')
  writeFileSync(
    file,
    [
      '[Molden Format]',
      '[Atoms] AU',
      'O   1   8   0.000000   0.000000   0.221600',
      'H   2   1   0.000000   1.430900  -0.886700',
      '[GTO]',
      'x',
    ].join('\n'),
    'utf8',
  )
  const { atoms } = readStructure(file)
  assert.equal(atoms.length, 2)
  assert.ok(Math.abs(atoms[0].z - 0.1173) < 1e-3)
})

test('视图包可以没有体数据（只看优化后的几何）', () => {
  const pack = buildViewPack({
    outDir: dir,
    name: 'opt',
    title: '优化后的几何',
    volumes: [],
    atoms: [
      { element: 'O', x: 0, y: 0, z: 0.1173 },
      { element: 'H', x: 0, y: 0.7572, z: -0.4692 },
      { element: 'H', x: 0, y: -0.7572, z: -0.4692 },
    ],
    bonds: [[0, 1], [0, 2]],
  })
  assert.equal(pack.meta.volumes.length, 0)
  assert.equal(pack.meta.atoms.length, 3)
  assert.equal(pack.meta.bonds.length, 2)
})

test('视图包默认配色按顺序取，不写死红蓝', () => {
  const atomLine = ['O 0 0 0', 'H 0 0 1']
  const share = (file) => {
    writeFileSync(
      file,
      [
        'Generated by Multiwfn',
        'comment',
        `2 ${atomLine[0].split(' ')[1]} ${atomLine[0].split(' ')[2]} ${atomLine[0].split(' ')[3]} 1`,
        '4 1 0 0',
        '4 0 1 0',
        '4 0 0 1',
        'O 8 0 0 0 0',
        'H 1 0 0 1.889 0',
        ...Array.from({ length: 64 }, (_, i) => String((i % 7) * 0.01)),
      ].join('\n'),
      'utf8',
    )
    return file
  }
  const a = share(path.join(dir, 'a.cub'))
  const b = share(path.join(dir, 'b.cub'))
  const pack = buildViewPack({ outDir: dir, name: 'two', volumes: [{ file: a, name: 'alpha' }, { file: b, name: 'beta' }] })
  assert.equal(pack.meta.volumes.length, 2)
  assert.notDeepEqual(pack.meta.volumes[0].color, pack.meta.volumes[1].color)
  assert.equal(pack.meta.volumes[0].label, 'alpha')
})
