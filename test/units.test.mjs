import assert from 'node:assert/strict'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import test from 'node:test'

import { verifyCube, verifyFile } from '../lib/artifacts.js'
import { buildVmdScript } from '../lib/tasks/render.js'
import { safeName, buildDirectScript } from '../lib/tasks/orca-remote.js'

const dir = mkdtempSync(path.join(tmpdir(), 'chemflow-test-'))

/**
 * 造一个 cube：头 6 行 + 数据。
 *
 * @param {string} name
 * @param {{ natoms?: number, n?: number, truncate?: boolean }} [options]
 */
function makeCube(name, options = {}) {
  const { natoms = 2, n = 10, truncate = false } = options
  const lines = [
    'Generated by Multiwfn',
    'totally N grid points',
    `${natoms} 0.0 0.0 0.0`,
    `${n} 0.1 0.0 0.0`,
    `${n} 0.0 0.1 0.0`,
    `${n} 0.0 0.0 0.1`,
  ]
  for (let i = 0; i < natoms; i += 1) lines.push('6 6.0 0.0 0.0 0.0')
  const total = n * n * n
  const data = []
  const perLine = 6
  for (let i = 0; i < total; i += 1) {
    data.push('  1.00000E-03')
    if ((i + 1) % perLine === 0) data.push('\n')
  }
  const body = truncate ? data.slice(0, Math.floor(data.length / 4)).join('') : data.join('')
  const file = path.join(dir, name)
  writeFileSync(file, `${lines.join('\n')}\n${body}`, 'utf8')
  return file
}

test('verifyFile 认得出缺失与过小', () => {
  assert.equal(verifyFile(path.join(dir, 'nope.cub')).ok, false)
  const tiny = path.join(dir, 'tiny.txt')
  writeFileSync(tiny, 'x')
  assert.equal(verifyFile(tiny, { minBytes: 100 }).ok, false)
})

test('verifyCube 接受头部与数据量自洽的 cube', () => {
  const file = makeCube('good.cub')
  const result = verifyCube(file, { minBytes: 100 })
  assert.equal(result.ok, true)
  assert.equal(result.cube.natoms, 2)
  assert.equal(result.cube.nx, 10)
  assert.equal(result.cube.points, 1000)
})

test('verifyCube 拦住被截断的数据（每点字节数明显偏低）', () => {
  const file = makeCube('truncated.cub', { truncate: true })
  const result = verifyCube(file, { minBytes: 100 })
  assert.equal(result.ok, false)
  assert.match(result.reason, /数据可能没写完/)
})

test('buildVmdScript 只写 .bmp，并把骨架/颜色/视角都写进去', () => {
  const script = buildVmdScript({
    molecules: [
      { file: 'C:\\a b\\hole.cub', style: 'both', iso: 0.003, colorId: 21 },
      { file: 'C:\\a b\\electron.cub', style: 'isosurface', iso: 0.003, colorId: 31 },
    ],
    scale: 1.8,
    rotate: [['x', -12]],
    outFile: 'C:\\run\\render.bmp',
  })
  assert.match(script, /render TachyonInternal \{C:\\run\\render\.bmp\}/)
  assert.doesNotMatch(script, /\.png/)
  assert.match(script, /mol new \{C:\\a b\\hole\.cub\} type cube/)
  assert.match(script, /mol modselect 1 0 "not name H"/)
  assert.match(script, /display resize 1600 1200/)
  assert.match(script, /rotate x by -12/)
})

test('safeName 把危险字符换掉，空名兜底', () => {
  assert.equal(safeName('job/../x'), 'job_.._x')
  assert.equal(safeName('中文'), '__')
  assert.ok(safeName('').startsWith('orca_'))
})

test('buildDirectScript 带齐 ORCA/MPI 环境与退出码回写', () => {
  const script = buildDirectScript({ name: 'job' })
  assert.match(script, /LD_LIBRARY_PATH="\/opt\/software\/orca-5\.0\.3/)
  assert.match(script, /orca-5\.0\.3\/orca" "job\.inp" > "job\.out"/)
  assert.match(script, /echo "\$code" > "job\.exit"/)
})
